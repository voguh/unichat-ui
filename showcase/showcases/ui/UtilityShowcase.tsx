const SCROLL_ITEMS = Array.from({ length: 40 }, (_, index) => `Message #${index + 1}`);

function nextProgress(current: number): number {
    if (current < 100) {
        return current + 5;
    }

    return 0;
}

export function ProgressShowcase(): PReact.ComponentChildren {
    const [value, setValue] = useState(0);

    useEffect(() => {
        const interval = setInterval(() => setValue(nextProgress), 300);
        return () => clearInterval(interval);
    }, []);

    return (
        <ShowcasePage
            title="Progress"
            description="Linear progress bar with role=progressbar."
            usage={`
import { Progress } from "@voguh/unichat-ui/components/ui/Progress";

<Progress value={uploaded} max={total} label="Uploading" />
`}
            api={[
                {
                    name: "Progress",
                    props: "HTMLAttributes<HTMLDivElement>",
                    ref: "HTMLDivElement",
                    nonStandard: [
                        {
                            name: "value",
                            type: "number | null",
                            description: "Required: current value; null shows an indeterminate bar."
                        },
                        { name: "max", type: "number", defaultValue: "100", description: "Value of a full bar." },
                        {
                            name: "label",
                            type: "ComponentChildren",
                            description: "Visible label, also the bar's accessible name."
                        }
                    ]
                }
            ]}
        >
            <Example title="Determinate" vertical>
                <Progress value={value} label="Uploading" />
            </Example>
            <Example title="Indeterminate" vertical>
                <Progress value={null} />
            </Example>
        </ShowcasePage>
    );
}

